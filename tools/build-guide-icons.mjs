// Generate src/lib/guide/icons.ts from Lucide (https://lucide.dev, ISC/MIT) icon
// SVGs. Run once, or when adding section icons; the OUTPUT is committed so both the
// app and the build import it -- there is NO runtime third-party request. Lucide is
// credited in the About dialog.
//
//   node tools/build-guide-icons.mjs
//
// Keys are guide section ids (content/guide/index.json "icon"); values are the
// inner SVG markup, rendered inside a 24x24 currentColor stroke icon by GuideIcon.

import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const VERSION = '0.544.0';

// guide section id -> Lucide icon name
const MAP = {
  welcome: 'house',
  contacts: 'users',
  meetings: 'calendar-days',
  agendas: 'file-text',
  'trash-recycling': 'recycle',
  'pickup-schedule': 'calendar-check',
  permits: 'clipboard-check',
  events: 'trees',
  utilities: 'droplets',
  'property-taxes': 'receipt',
  elections: 'vote',
  transit: 'bus',
  roads: 'construction',
  'snow-and-ice': 'snowflake',
  'ops-status': 'clipboard-list',
  help: 'life-buoy',
  'get-involved': 'heart-handshake',
  worship: 'church',
  ordinances: 'scale',
  'video-tour': 'video',
};

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'lib', 'guide', 'icons.ts');

const icons = {};
for (const [id, name] of Object.entries(MAP)) {
  const res = await fetch(`https://unpkg.com/lucide-static@${VERSION}/icons/${name}.svg`);
  if (!res.ok) {
    console.warn(`  skip ${id} (${name}): HTTP ${res.status}`);
    continue;
  }
  const svg = await res.text();
  const inner = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>[\s\S]*$/, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  icons[id] = inner;
}

const header =
  '// AUTO-GENERATED by tools/build-guide-icons.mjs from Lucide (https://lucide.dev,\n' +
  '// ISC/MIT). Do not edit by hand -- re-run the generator to add icons. Credited in About.\n\n';
writeFileSync(OUT, `${header}export const ICONS: Record<string, string> = ${JSON.stringify(icons, null, 2)};\n`, 'utf8');
console.log(`Wrote ${OUT} (${Object.keys(icons).length} icons)`);
